"""Existing cims physical-return, count, reason and adjustment tables."""

from sqlalchemy import (
    BigInteger,
    Boolean,
    Column,
    Date,
    DateTime,
    Integer,
    MetaData,
    Numeric,
    Table,
    Text,
)
from sqlalchemy.dialects.postgresql import UUID

metadata = MetaData(schema="cims")

returns = Table(
    "sales_return",
    metadata,
    Column("sales_return_id", UUID(as_uuid=True), primary_key=True),
    Column("tenant_id", UUID(as_uuid=True)),
    Column("return_no", Text),
    Column("status", Text),
    Column("customer_id", UUID(as_uuid=True)),
    Column("shipment_id", UUID(as_uuid=True)),
    Column("location_id", UUID(as_uuid=True)),
    Column("restock_location_id", UUID(as_uuid=True)),
    Column("quarantine_location_id", UUID(as_uuid=True)),
    Column("reason_code_id", UUID(as_uuid=True)),
    Column("reason_note", Text),
    Column("return_date", Date),
    Column("inspection_required", Boolean),
    Column("total_quantity", Numeric(18, 4)),
    Column("approved_by", UUID(as_uuid=True)),
    Column("approved_at", DateTime(timezone=True)),
    Column("received_at", DateTime(timezone=True)),
    Column("created_by", UUID(as_uuid=True)),
    Column("created_at", DateTime(timezone=True)),
)
return_lines = Table(
    "sales_return_line",
    metadata,
    Column("sales_return_line_id", UUID(as_uuid=True), primary_key=True),
    Column("tenant_id", UUID(as_uuid=True)),
    Column("sales_return_id", UUID(as_uuid=True)),
    Column("line_no", Integer),
    Column("item_id", UUID(as_uuid=True)),
    Column("uom_id", UUID(as_uuid=True)),
    Column("quantity", Numeric(18, 4)),
    Column("quantity_in_stock_uom", Numeric(18, 4)),
    Column("condition", Text),
    Column("restock", Boolean),
)
counts = Table(
    "audit_count",
    metadata,
    Column("audit_count_id", UUID(as_uuid=True), primary_key=True),
    Column("tenant_id", UUID(as_uuid=True)),
    Column("count_no", Text),
    Column("status", Text),
    Column("location_id", UUID(as_uuid=True)),
    Column("count_type", Text),
    Column("blind_count", Boolean),
    Column("freeze_location", Boolean),
    Column("snapshot_at", DateTime(timezone=True)),
    Column("started_at", DateTime(timezone=True)),
    Column("submitted_at", DateTime(timezone=True)),
    Column("approved_at", DateTime(timezone=True)),
    Column("approved_by", UUID(as_uuid=True)),
    Column("notes", Text),
    Column("created_by", UUID(as_uuid=True)),
    Column("created_at", DateTime(timezone=True)),
)
count_lines = Table(
    "audit_count_line",
    metadata,
    Column("audit_count_line_id", UUID(as_uuid=True), primary_key=True),
    Column("tenant_id", UUID(as_uuid=True)),
    Column("audit_count_id", UUID(as_uuid=True)),
    Column("item_id", UUID(as_uuid=True)),
    Column("system_quantity", Numeric(18, 4)),
    Column("counted_quantity", Numeric(18, 4)),
    Column("recount_quantity", Numeric(18, 4)),
    Column("reason_code_id", UUID(as_uuid=True)),
    Column("adjustment_id", UUID(as_uuid=True)),
    Column("counted_by", UUID(as_uuid=True)),
    Column("counted_at", DateTime(timezone=True)),
    Column("approved_by", UUID(as_uuid=True)),
    Column("approved_at", DateTime(timezone=True)),
)
adjustments = Table(
    "adjustment",
    metadata,
    Column("adjustment_id", UUID(as_uuid=True), primary_key=True),
    Column("tenant_id", UUID(as_uuid=True)),
    Column("adjustment_no", Text),
    Column("status", Text),
    Column("location_id", UUID(as_uuid=True)),
    Column("item_id", UUID(as_uuid=True)),
    Column("quantity_delta", Numeric(18, 4)),
    Column("value_delta", Numeric(20, 4)),
    Column("new_unit_cost", Numeric(20, 6)),
    Column("reason_code_id", UUID(as_uuid=True)),
    Column("reason_note", Text),
    Column("requested_by", UUID(as_uuid=True)),
    Column("approved_by", UUID(as_uuid=True)),
    Column("approved_at", DateTime(timezone=True)),
    Column("posted_at", DateTime(timezone=True)),
    Column("ledger_entry_id", BigInteger),
    Column("reversal_of_adjustment_id", UUID(as_uuid=True)),
)
reasons = Table(
    "reason_code",
    metadata,
    Column("reason_code_id", UUID(as_uuid=True), primary_key=True),
    Column("tenant_id", UUID(as_uuid=True)),
    Column("code", Text),
    Column("name", Text),
    Column("applies_to", Text),
    Column("requires_approval", Boolean),
    Column("is_active", Boolean),
    Column("is_system", Boolean),
)
actors = Table(
    "app_user",
    metadata,
    Column("user_id", UUID(as_uuid=True), primary_key=True),
    Column("tenant_id", UUID(as_uuid=True)),
    Column("email", Text),
    Column("full_name", Text),
    Column("status", Text),
    Column("is_tenant_owner", Boolean),
)
