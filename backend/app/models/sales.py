"""Existing sales-order and reservation tables; ledger posting stays in inventory."""

from sqlalchemy import (
    Boolean,
    Column,
    Date,
    DateTime,
    Integer,
    MetaData,
    Numeric,
    String,
    Table,
    Text,
)
from sqlalchemy.dialects.postgresql import ENUM, UUID

from app.models.inventory import document_kind

metadata = MetaData(schema="cims")
reservation_state = ENUM(
    "ACTIVE",
    "RELEASED",
    "CONSUMED",
    "EXPIRED",
    name="reservation_state_t",
    schema="cims",
    create_type=False,
)

orders = Table(
    "sales_order",
    metadata,
    Column("sales_order_id", UUID(as_uuid=True), primary_key=True),
    Column("tenant_id", UUID(as_uuid=True), nullable=False),
    Column("order_no", Text),
    Column("document_kind", document_kind),
    Column("status", Text),
    Column("sales_source", Text),
    Column("revision", Integer),
    Column("customer_id", UUID(as_uuid=True)),
    Column("location_id", UUID(as_uuid=True)),
    Column("order_date", Date),
    Column("expected_ship_date", Date),
    Column("payment_terms_days", Integer),
    Column("place_of_supply_state", String),
    Column("is_b2c", Boolean),
    Column("credit_check_passed", Boolean),
    Column("credit_limit_at_order", Numeric(20, 4)),
    Column("subtotal", Numeric(20, 4)),
    Column("discount_total", Numeric(20, 4)),
    Column("tax_total", Numeric(20, 4)),
    Column("round_off", Numeric(20, 4)),
    Column("grand_total", Numeric(20, 4)),
    Column("notes", Text),
    Column("confirmed_at", DateTime(timezone=True)),
    Column("cancelled_at", DateTime(timezone=True)),
    Column("cancel_reason", Text),
    Column("created_by", UUID(as_uuid=True)),
    Column("created_at", DateTime(timezone=True)),
    Column("updated_at", DateTime(timezone=True)),
)

lines = Table(
    "sales_order_line",
    metadata,
    Column("sales_order_line_id", UUID(as_uuid=True), primary_key=True),
    Column("tenant_id", UUID(as_uuid=True), nullable=False),
    Column("sales_order_id", UUID(as_uuid=True)),
    Column("line_no", Integer),
    Column("item_id", UUID(as_uuid=True)),
    Column("uom_id", UUID(as_uuid=True)),
    Column("quantity", Numeric(18, 4)),
    Column("quantity_in_stock_uom", Numeric(18, 4)),
    Column("unit_price", Numeric(20, 6)),
    Column("discount_pct", Numeric(7, 4)),
    Column("discount_amount", Numeric(20, 4)),
    Column("tax_rate", Numeric(7, 4)),
    Column("taxable_value", Numeric(20, 4)),
    Column("tax_amount", Numeric(20, 4)),
    Column("line_total", Numeric(20, 4)),
    Column("hsn_sac_code", Text),
    Column("location_id", UUID(as_uuid=True)),
    Column("reserved_quantity", Numeric(18, 4)),
    Column("shipped_quantity", Numeric(18, 4)),
    Column("invoiced_quantity", Numeric(18, 4)),
    Column("cancelled_quantity", Numeric(18, 4)),
    Column("cost_center_id", UUID(as_uuid=True)),
)

reservations = Table(
    "reservation",
    metadata,
    Column("reservation_id", UUID(as_uuid=True), primary_key=True),
    Column("tenant_id", UUID(as_uuid=True), nullable=False),
    Column("item_id", UUID(as_uuid=True)),
    Column("location_id", UUID(as_uuid=True)),
    Column("sales_order_id", UUID(as_uuid=True)),
    Column("sales_order_line_id", UUID(as_uuid=True)),
    Column("quantity", Numeric(18, 4)),
    Column("consumed_quantity", Numeric(18, 4)),
    Column("state", reservation_state),
    Column("expires_at", DateTime(timezone=True)),
    Column("created_at", DateTime(timezone=True)),
    Column("released_at", DateTime(timezone=True)),
    Column("release_reason", Text),
)

pick_scans = Table(
    "pick_scan",
    metadata,
    Column("pick_scan_id", UUID(as_uuid=True), primary_key=True),
    Column("tenant_id", UUID(as_uuid=True), nullable=False),
    Column("sales_order_id", UUID(as_uuid=True)),
    Column("sales_order_line_id", UUID(as_uuid=True)),
    Column("reservation_id", UUID(as_uuid=True)),
    Column("item_id", UUID(as_uuid=True)),
    Column("location_id", UUID(as_uuid=True)),
    Column("scanned_code", Text),
    Column("quantity", Numeric(18, 4)),
    Column("shipped_quantity", Numeric(18, 4)),
    Column("is_override", Boolean),
    Column("override_reason", Text),
    Column("scanned_by", UUID(as_uuid=True)),
    Column("created_at", DateTime(timezone=True)),
)

packages = Table(
    "package",
    metadata,
    Column("package_id", UUID(as_uuid=True), primary_key=True),
    Column("tenant_id", UUID(as_uuid=True), nullable=False),
    Column("package_no", Text),
    Column("document_kind", document_kind),
    Column("status", Text),
    Column("sales_order_id", UUID(as_uuid=True)),
    Column("location_id", UUID(as_uuid=True)),
    Column("packed_by", UUID(as_uuid=True)),
    Column("packed_at", DateTime(timezone=True)),
    Column("weight_kg", Numeric(12, 3)),
    Column("length_cm", Numeric(12, 3)),
    Column("width_cm", Numeric(12, 3)),
    Column("height_cm", Numeric(12, 3)),
    Column("carrier", Text),
    Column("tracking_no", Text),
    Column("notes", Text),
    Column("created_at", DateTime(timezone=True)),
)

package_lines = Table(
    "package_line",
    metadata,
    Column("package_line_id", UUID(as_uuid=True), primary_key=True),
    Column("tenant_id", UUID(as_uuid=True), nullable=False),
    Column("package_id", UUID(as_uuid=True)),
    Column("sales_order_line_id", UUID(as_uuid=True)),
    Column("item_id", UUID(as_uuid=True)),
    Column("quantity", Numeric(18, 4)),
)

shipments = Table(
    "shipment",
    metadata,
    Column("shipment_id", UUID(as_uuid=True), primary_key=True),
    Column("tenant_id", UUID(as_uuid=True), nullable=False),
    Column("shipment_no", Text),
    Column("document_kind", document_kind),
    Column("status", Text),
    Column("sales_order_id", UUID(as_uuid=True)),
    Column("from_location_id", UUID(as_uuid=True)),
    Column("is_partial", Boolean),
    Column("shipped_at", DateTime(timezone=True)),
    Column("carrier", Text),
    Column("tracking_no", Text),
    Column("tracking_url", Text),
    Column("notes", Text),
    Column("created_by", UUID(as_uuid=True)),
    Column("created_at", DateTime(timezone=True)),
    Column("updated_at", DateTime(timezone=True)),
)

shipment_lines = Table(
    "shipment_line",
    metadata,
    Column("shipment_line_id", UUID(as_uuid=True), primary_key=True),
    Column("tenant_id", UUID(as_uuid=True), nullable=False),
    Column("shipment_id", UUID(as_uuid=True)),
    Column("sales_order_line_id", UUID(as_uuid=True)),
    Column("item_id", UUID(as_uuid=True)),
    Column("quantity", Numeric(18, 4)),
    Column("quantity_in_stock_uom", Numeric(18, 4)),
    Column("unit_cost", Numeric(20, 6)),
    Column("package_id", UUID(as_uuid=True)),
    Column("ledger_entry_id", Integer),
)

shipment_packages = Table(
    "shipment_package",
    metadata,
    Column("tenant_id", UUID(as_uuid=True), primary_key=True),
    Column("shipment_id", UUID(as_uuid=True), primary_key=True),
    Column("package_id", UUID(as_uuid=True), primary_key=True),
)
