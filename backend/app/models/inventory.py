"""Read mappings for existing stock tables. Quantity posting belongs to inventory services."""

from sqlalchemy import (
    BigInteger,
    Boolean,
    Column,
    Date,
    DateTime,
    Integer,
    MetaData,
    Numeric,
    String,
    Table,
    Text,
)
from sqlalchemy.dialects.postgresql import ENUM, JSONB, UUID

metadata = MetaData(schema="cims")
stock_state = ENUM(
    "PHYSICAL",
    "ACCOUNTING",
    "COMMITTED",
    "INCOMING",
    name="stock_state_t",
    schema="cims",
    create_type=False,
)
direction = ENUM("IN", "OUT", name="direction_t", schema="cims", create_type=False)
document_kind = ENUM(
    "SALES_ORDER",
    "PURCHASE_ORDER",
    "TRANSFER_ORDER",
    "INVOICE",
    "CREDIT_NOTE",
    "DEBIT_NOTE",
    "BILL",
    "EXPENSE",
    "SHIPMENT",
    "PACKAGE",
    "PURCHASE_RECEIVE",
    "ADJUSTMENT",
    "AUDIT_COUNT",
    "SALES_RETURN",
    "DELIVERY_CHALLAN",
    "REQUISITION",
    "ISSUE_NOTE",
    "WORK_ORDER",
    "OPENING_STOCK",
    name="document_kind_t",
    schema="cims",
    create_type=False,
)

balances = Table(
    "stock_balance",
    metadata,
    Column("tenant_id", UUID(as_uuid=True)),
    Column("item_id", UUID(as_uuid=True)),
    Column("location_id", UUID(as_uuid=True)),
    Column("physical_on_hand", Numeric(18, 4)),
    Column("accounting_on_hand", Numeric(18, 4)),
    Column("committed", Numeric(18, 4)),
    Column("incoming", Numeric(18, 4)),
    Column("avg_unit_cost", Numeric(20, 6)),
    Column("inventory_value", Numeric(20, 4)),
    Column("version", BigInteger),
    Column("last_movement_at", DateTime(timezone=True)),
)
locations = Table(
    "location",
    metadata,
    Column("tenant_id", UUID(as_uuid=True)),
    Column("location_id", UUID(as_uuid=True)),
    Column("location_type_id", UUID(as_uuid=True)),
    Column("code", String),
    Column("name", String),
    Column("is_active", Boolean),
    Column("address_line1", Text),
    Column("city", Text),
    Column("state_code", String),
    Column("tax_registration_id", UUID(as_uuid=True)),
    Column("pincode", Text),
)
location_types = Table(
    "location_type",
    metadata,
    Column("tenant_id", UUID(as_uuid=True)),
    Column("location_type_id", UUID(as_uuid=True)),
    Column("code", String),
    Column("is_in_transit", Boolean),
    Column("is_storage", Boolean),
    Column("name", Text),
    Column("is_system", Boolean),
)
ledger = Table(
    "stock_ledger_entry",
    metadata,
    Column("tenant_id", UUID(as_uuid=True)),
    Column("entry_id", BigInteger),
    Column("occurred_at", DateTime(timezone=True)),
    Column("item_id", UUID(as_uuid=True)),
    Column("location_id", UUID(as_uuid=True)),
    Column("stock_state", stock_state),
    Column("direction", direction),
    Column("quantity", Numeric(18, 4)),
    Column("signed_quantity", Numeric(18, 4)),
    Column("unit_cost", Numeric(20, 6)),
    Column("source_document_type", document_kind),
    Column("source_document_id", UUID(as_uuid=True)),
    Column("source_document_no", String),
    Column("physical_balance_after", Numeric(18, 4)),
    Column("movement_type_id", UUID(as_uuid=True)),
    Column("source_document_line_id", UUID(as_uuid=True)),
    Column("idempotency_key", Text),
    Column("reversal_of_entry_id", BigInteger),
    Column("is_reversal", Boolean),
    Column("reason_code_id", UUID(as_uuid=True)),
    Column("reason_note", Text),
    Column("created_by", UUID(as_uuid=True)),
    Column("cost_center_id", UUID(as_uuid=True)),
)
fifo_layers = Table(
    "fifo_layer",
    metadata,
    Column("tenant_id", UUID(as_uuid=True)),
    Column("fifo_layer_id", BigInteger),
    Column("item_id", UUID(as_uuid=True)),
    Column("location_id", UUID(as_uuid=True)),
    Column("received_at", DateTime(timezone=True)),
    Column("remaining_qty", Numeric(18, 4)),
    Column("unit_cost", Numeric(20, 6)),
    Column("original_qty", Numeric(18, 4)),
    Column("source_ledger_entry_id", BigInteger),
    Column("source_ledger_entry_at", DateTime(timezone=True)),
)
fifo_consumptions = Table(
    "fifo_consumption",
    metadata,
    Column("tenant_id", UUID(as_uuid=True)),
    Column("fifo_layer_id", BigInteger),
    Column("ledger_entry_id", BigInteger),
    Column("ledger_entry_at", DateTime(timezone=True)),
    Column("quantity", Numeric(18, 4)),
    Column("unit_cost", Numeric(20, 6)),
)

movement_types = Table(
    "movement_type",
    metadata,
    Column("movement_type_id", UUID(as_uuid=True)),
    Column("tenant_id", UUID(as_uuid=True)),
    Column("code", Text),
    Column("name", Text),
    Column("stock_state", stock_state),
    Column("direction_hint", direction),
    Column("requires_reason", Boolean),
    Column("is_system", Boolean),
    Column("is_active", Boolean),
)
number_sequences = Table(
    "number_sequence",
    metadata,
    Column("tenant_id", UUID(as_uuid=True)),
    Column("document_kind", document_kind),
    Column("fiscal_year", Text),
    Column("prefix", Text),
    Column("next_value", BigInteger),
    Column("padding", Integer),
    Column("suffix", Text),
)
idempotency_keys = Table(
    "idempotency_key",
    metadata,
    Column("tenant_id", UUID(as_uuid=True)),
    Column("key", Text),
    Column("scope", Text),
    Column("request_fingerprint", Text),
    Column("response_status", Integer),
    Column("response_body", JSONB),
)
opening_stock = Table(
    "opening_stock",
    metadata,
    Column("opening_stock_id", UUID(as_uuid=True)),
    Column("tenant_id", UUID(as_uuid=True)),
    Column("document_no", Text),
    Column("business_date", Date),
    Column("status", Text),
    Column("version", BigInteger),
    Column("notes", Text),
    Column("created_by", UUID(as_uuid=True)),
    Column("posted_by", UUID(as_uuid=True)),
    Column("created_at", DateTime(timezone=True)),
    Column("posted_at", DateTime(timezone=True)),
)
opening_lines = Table(
    "opening_stock_line",
    metadata,
    Column("opening_stock_line_id", UUID(as_uuid=True)),
    Column("tenant_id", UUID(as_uuid=True)),
    Column("opening_stock_id", UUID(as_uuid=True)),
    Column("line_no", Integer),
    Column("item_id", UUID(as_uuid=True)),
    Column("location_id", UUID(as_uuid=True)),
    Column("entered_uom_id", UUID(as_uuid=True)),
    Column("entered_quantity", Numeric(24, 10)),
    Column("conversion_factor", Numeric(24, 10)),
    Column("stock_uom_id", UUID(as_uuid=True)),
    Column("stock_quantity", Numeric(18, 4)),
    Column("unit_cost", Numeric(20, 6)),
    Column("item_catalog_version", BigInteger),
    Column("sku_snapshot", Text),
    Column("item_name_snapshot", Text),
    Column("stock_unit_snapshot", Text),
    Column("location_code_snapshot", Text),
)
outbox_events = Table(
    "outbox_event",
    metadata,
    Column("outbox_event_id", UUID(as_uuid=True)),
    Column("tenant_id", UUID(as_uuid=True)),
    Column("event_type", Text),
    Column("aggregate_id", UUID(as_uuid=True)),
    Column("payload", JSONB),
    Column("status", Text),
    Column("attempts", Integer),
    Column("available_at", DateTime(timezone=True)),
    Column("created_at", DateTime(timezone=True)),
    Column("completed_at", DateTime(timezone=True)),
    Column("last_error_code", Text),
)
